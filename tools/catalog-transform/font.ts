function rowsFor(char: string): string[] | undefined {
	if (PATTERNS[char]) return PATTERNS[char];
	return PATTERNS[char.toUpperCase()];
}

/** Number of glyph columns a string occupies (glyphs + single-column gaps). */
export function labelWidthUnits(text: string): number {
	if (text.length === 0) return 0;
	return text.length * GLYPH_COLS + (text.length - 1);
}

/**
 * Build SVG path data (a set of unit squares) for a label at `(x, y)`, where
 * `cell` is the pixel size of one font cell. Unknown characters render blank.
 */
export function labelPathData(
	text: string,
	x: number,
	y: number,
	cell: number,
): string {
	let d = "";
	let cursor = x;
	for (const char of text) {
		const rows = rowsFor(char);
		if (rows) {
			for (let row = 0; row < GLYPH_ROWS; row++) {
				const line = rows[row];
				for (let col = 0; col < GLYPH_COLS; col++) {
					if (line[col] === "#") {
						const px = cursor + col * cell;
						const py = y + row * cell;
						d += `M${px} ${py}h${cell}v${cell}h${-cell}z`;
					}
				}
			}
		}
		cursor += (GLYPH_COLS + 1) * cell;
	}
	return d;
}
